console.log(checkArrEl([{name: 'Ivan', age: 21}, {name: 'Dmitry', age: 21}], checkObj)); 

/** 7
 * Напишите функцию, которая принимает массив строк и функцию преобразования.
Функция должна возвращать объект, где ключи — это исходные строки, а значения
— результаты применения функции преобразования к каждой строке. Эта функция
принимает одну строку и возвращает новое значение, которое может быть числом,
другой строкой, объектом или любым другим типом данных.
 */

function arrToObj(arr, newFn) {
    let result = {};
    arr.forEach(str => {
        result[str] = newFn(str);
    });
    return result;
}

const arr = ["Dzmitry", "Ivan", "Sasha,", "Aleh"];
const newFn = str => str.length;

console.log(arrToObj(arr, newFn));


