/** 3
 * Напишите функцию, которая принимает массив объектов с полями name и age, и
группирует их в объект, где ключи — это возраст, а значения — массивы имен
людей этого возраста.
 */

const arrDataNameAge = [
    {name: 'Ivan', age : 18},
    {name: 'Dzmitry', age : 21},
    {name: 'Anton', age : 24}
]

function groupDataFromArray (arrDataNameAge) {
    let result = {};

    arrDataNameAge.forEach(person => {
        if (result[person.age]) {
            result[person.age].push(person.name);
        } else {
            result[person.age] = [person.name];
        }
    });

    return result;
}

console.log(groupDataFromArray(arrDataNameAge));

/** 4
 * Напишите функцию isPalindrome, которая проверяет, является ли заданная строка
палиндромом. Палиндром — это слово, фраза или последовательность, которые
читаются одинаково как в прямом, так и в обратном порядке (без учета пробелов,
знаков препинания и регистра). Игнорируйте пробелы и знаки препинания, а строки
из одного символа следует считать палиндромами (например, &quot;a&quot;)
 */

function isPalindrome(word) {
    let startStr = word.toLowerCase().replace(/[^a-z0-9]/g, "") // "^" === "!="" , 'g' - flag for replacing
    let finalStr = startStr.split("").reverse().join("")

    return startStr === finalStr
}

console.log(isPalindrome("lol"))
console.log(isPalindrome("garage"))
console.log(isPalindrome("garag"))
 
