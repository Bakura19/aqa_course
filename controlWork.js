async function runPrm(fun) {
    let prm = []
    fun.forEach(fn => prm.push(fn()))
    return Promise.all(prm) //Promise.all для приёмки массива промисов и последующиего возвращения нового промиса
}
let fun = [
    () => Promise.resolve(1000),
    () => Promise.resolve(2000),
    () => Promise.resolve(3000)
];

